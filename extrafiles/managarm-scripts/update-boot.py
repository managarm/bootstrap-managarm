#!/usr/bin/env python3

# Generates the boot files on the ESP from ROOT/etc/managarm/{partitions,boot}.toml.
# The host (update-image.py) and the target run this script, so it only uses the stdlib.

import argparse
import contextlib
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
import tomllib

# Revision of the CLI interface, bumped when we change the CLI interface that other scripts rely on.
# Prior changes:
# Revision 2: esp-contents writes all of the ESP and its stamp.
# The exact format of the CLI_REVISION line MUST be preserved as it is parsed by other scripts with a regexp.
CLI_REVISION = 2

ARCHES = ["x86_64", "aarch64", "riscv64"]
BIOS_BOOT_TYPE = "21686148-6449-6E6F-744E-656564454649"
EIR_FILES = {
    "x86_64": ["eir-limine", "eir-mb2", "eir-uefi"],
    "aarch64": ["eir-limine", "eir-linux.bin", "eir-uefi"],
    "riscv64": ["eir-limine", "eir-linux.bin", "eir-uefi"],
}
EFI_LOADERS = {
    "x86_64": "BOOTX64.EFI",
    "aarch64": "BOOTAA64.EFI",
    "riscv64": "BOOTRISCV64.EFI",
}
STAMP_PATH = "managarm/update-boot.json"
# Bump when the ESP has to be rewritten even though the generated files are unchanged.
STAMP_VERSION = 1


class ConfigError(Exception):
    pass


class Config:
    __slots__ = (
        "root_partuuid",
        "esp_partuuid",
        "cmdline",
    )

    @staticmethod
    def load(root):
        def read(name, *, required):
            path = os.path.join(root, "etc/managarm", name)
            try:
                with open(path, "rb") as f:
                    return path, tomllib.load(f)
            except FileNotFoundError:
                if required:
                    raise ConfigError(f"{path} does not exist")
                return path, {}
            except tomllib.TOMLDecodeError as e:
                raise ConfigError(f"{path}: {e}")

        def get(path, table, prefix, key, kind, *, required=False, default=None):
            if key not in table:
                if required:
                    raise ConfigError(f"{path}: {prefix}{key} is missing")
                return default
            value = table[key]
            if not isinstance(value, kind):
                kind_name = {str: "string", dict: "table"}[kind]
                raise ConfigError(f"{path}: {prefix}{key} must be a {kind_name}")
            return value

        # Newer versions may add keys; they must not break older versions of this script.
        def warn_unknown(path, table, prefix, known):
            for key in sorted(table.keys() - known):
                print(f"update-boot: Ignoring unknown key {prefix}{key} in {path}", file=sys.stderr)

        config = Config()

        # Written when the root is provisioned; all keys have defaults.
        path, data = read("boot.toml", required=False)
        warn_unknown(path, data, "", {"cmdline"})
        config.cmdline = get(path, data, "", "cmdline", str, default="")

        # Written once the partitions of the target disk are known.
        path, data = read("partitions.toml", required=True)
        warn_unknown(path, data, "", {"root", "esp"})

        root_part = get(path, data, "", "root", dict, required=True)
        warn_unknown(path, root_part, "root.", {"partuuid"})
        config.root_partuuid = get(path, root_part, "root.", "partuuid", str, required=True).lower()

        esp_part = get(path, data, "", "esp", dict, default={})
        warn_unknown(path, esp_part, "esp.", {"partuuid"})
        config.esp_partuuid = get(path, esp_part, "esp.", "partuuid", str)

        if not config.root_partuuid:
            raise ConfigError(f"{path}: root.partuuid is empty")
        return config


class LimineWriter:
    __slots__ = (
        "base_cmdline",
        "user_cmdline",
        "out",
        "_level",
    )

    def __init__(self, out, *, base_cmdline, user_cmdline):
        self.out = out
        self._level = 0
        self.base_cmdline = base_cmdline
        self.user_cmdline = user_cmdline

    def write_header(self):
        self.out.writelines(
            [
                "# Generated by update-boot.py, do not edit.\n",
                "timeout: 3\n",
                # First entry is the default submenu.
                "default_entry: 2\n",
            ]
        )

    @contextlib.contextmanager
    def submenu(self, title):
        indent = " " * 4 * self._level
        slashes = "/" * (self._level + 1)
        self._level += 1
        self.out.writelines([f"{indent}{slashes}{title}\n"])
        yield
        self._level -= 1

    def write_entry(self, title, *, protocol, extra_cmdline=None):
        indent = " " * 4 * self._level
        slashes = "/" * (self._level + 1)
        subindent = " " * 4 * (self._level + 1)

        eir = {
            "limine": "eir-limine",
            "linux": "eir-linux.bin",
            "multiboot2": "eir-mb2",
            "efi": "eir-uefi",
        }[protocol]

        self.out.writelines(
            [
                # This has to be first line.
                f"{indent}{slashes}{title}\n",
                f"{subindent}protocol: {protocol}\n",
                f"{subindent}path: boot():/managarm/{eir}\n",
            ]
        )
        if protocol in {"limine", "multiboot2", "linux"}:
            self.out.write(f"{subindent}module_path: boot():/managarm/initrd.cpio\n")

        # The user's options go last so that they override those of the entry.
        cmdlines = [*self.base_cmdline, extra_cmdline, self.user_cmdline]
        cmdline = " ".join(x for x in cmdlines if x)
        if cmdline:
            self.out.write(f"{subindent}cmdline: {cmdline}\n")


def name_of_protocol(protocol):
    return {
        "limine": "Limine",
        "linux": "Linux",
        "multiboot2": "MB2",
        "efi": "UEFI",
    }[protocol]


# The boot targets that the installation provides, judged by their unit files.
def installed_targets(root):
    unit_dir = os.path.join(root, "usr/lib/systemd/system")
    targets = {target for target in ["kmscon", "sddm"] if os.path.exists(os.path.join(unit_dir, f"{target}.target"))}
    if "kmscon" not in targets:
        raise ConfigError(f"{root}: kmscon.target does not exist, the kmscon package is required")
    return targets


def make_default_entries(writer, *, protocol, targets):
    entries = []
    if "sddm" in targets:
        entries.append(("SDDM", "systemd.unit=sddm.target"))
    entries.append(("kmscon", "systemd.unit=kmscon.target"))
    # plainfb only claims the boot framebuffer on a modeset, so the kernel log stays on screen.
    entries.append(("Headless", "systemd.unit=multi-user.target plainfb.force=1"))
    for title, extra_cmdline in entries:
        writer.write_entry(
            f"{title} (via {name_of_protocol(protocol)})",
            protocol=protocol,
            extra_cmdline=extra_cmdline,
        )


def make_extra_entries(writer, *, protocol):
    writer.write_entry(
        f"Profiling (via {name_of_protocol(protocol)})",
        protocol=protocol,
        extra_cmdline="kernel-profile",
    )


def write_live_menu(writer, *, arch, targets):
    writer.write_header()

    limine_available = arch in {"x86_64", "riscv64"}
    linux_available = arch in {"aarch64", "riscv64"}
    mb2_available = arch in {"x86_64"}

    # TODO: On RISC-V, we probably want to switch to eir-uefi but that is currently broken.
    if arch in {"x86_64", "aarch64", "riscv64"}:
        # Limine can be loaded either by UEFI or by BIOS on x86.
        # We can either use the Limine protocol or MB2 to cover both cases.
        default_protocol = "limine"
    else:
        # Since Limine itself must be loaded by UEFI on non-x86,
        # we can default to chainloading.
        default_protocol = "efi"

    with writer.submenu("+Managarm: default options"):
        make_default_entries(writer, protocol=default_protocol, targets=targets)

    with writer.submenu("Managarm: extra options"):
        make_extra_entries(writer, protocol=default_protocol)

    if default_protocol != "efi":
        with writer.submenu("Managarm: UEFI chainload"):
            make_default_entries(writer, protocol="efi", targets=targets)

    if limine_available and default_protocol != "limine":
        with writer.submenu("Managarm: Limine protocol"):
            make_default_entries(writer, protocol="limine", targets=targets)

    if linux_available:
        with writer.submenu("Managarm: Linux protocol"):
            make_default_entries(writer, protocol="linux", targets=targets)

    if mb2_available:
        with writer.submenu("Managarm: Multiboot2 protocol"):
            make_default_entries(writer, protocol="multiboot2", targets=targets)


def write_limine_conf(path, config, *, arch, targets):
    # eir detects e9 under QEMU on its own, so x86 needs no bochs.
    base_cmdline = [
        "serial" if arch != "x86_64" else None,
        f"root=PARTUUID={config.root_partuuid}",
    ]
    with open(path, "w") as f:
        writer = LimineWriter(f, base_cmdline=base_cmdline, user_cmdline=config.cmdline)
        write_live_menu(writer, arch=arch, targets=targets)


def cmd_esp_contents(args):
    config = Config.load(args.root)
    files, external = make_esp_tree(args.root, args.arch, config, args.esp_dir, has_bios_boot=args.bios_boot)
    write_stamp(os.path.join(args.esp_dir, STAMP_PATH), files, external)


# Partition nodes are numbered from zero, e.g. sda0 or nvme0n1p0.
def part_name(disk, idx):
    return f"{disk}p{idx}" if disk[-1].isdigit() else f"{disk}{idx}"


# Returns the ESP's disk and partition, and whether the disk has a BIOS boot partition.
def find_esp(partuuid):
    for disk in sorted(os.listdir("/sys/block")):
        # /sys/block also lists partitions; most fail here, and FAT passes as an empty MBR.
        res = subprocess.run(["sfdisk", "-J", f"/dev/{disk}"], capture_output=True, text=True)
        if res.returncode:
            continue
        parts = json.loads(res.stdout)["partitiontable"].get("partitions", [])
        for idx, part in enumerate(parts):
            if part.get("uuid", "").lower() == partuuid.lower():
                return disk, part_name(disk, idx), any(p["type"].upper() == BIOS_BOOT_TYPE for p in parts)
    raise ConfigError(f"no disk has a partition with the PARTUUID {partuuid}")


def hash_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def hash_tree(tree):
    files = {}
    for dirpath, _, names in os.walk(tree):
        for name in names:
            path = os.path.join(dirpath, name)
            files[os.path.relpath(path, tree)] = hash_file(path)
    return files


def write_stamp(path, files, external):
    with open(path, "w") as f:
        json.dump({"version": STAMP_VERSION, "files": files, "external": external}, f, indent=4, sort_keys=True)


# Returns None if the stamp is missing or unusable, which makes the caller rewrite the ESP.
def read_stamp(esp, mtools_env):
    res = subprocess.run(["mtype", "-i", f"/dev/{esp}", f"::{STAMP_PATH}"], capture_output=True, env=mtools_env)
    if res.returncode:
        return None
    # This also catches a stamp that is not valid UTF-8.
    try:
        stamp = json.loads(res.stdout)
    except ValueError:
        return None
    if not isinstance(stamp, dict) or stamp.get("version") != STAMP_VERSION:
        return None
    if not isinstance(stamp.get("files"), dict) or not isinstance(stamp.get("external"), dict):
        return None
    return stamp


def make_esp_tree(root, arch, config, tree, *, has_bios_boot):
    bin_dir = os.path.join(root, "usr/managarm/bin")
    limine_dir = os.path.join(root, "usr/share/limine")

    os.makedirs(os.path.join(tree, "EFI/BOOT"))
    os.makedirs(os.path.join(tree, "managarm"))

    subprocess.run(
        [sys.executable, os.path.join(bin_dir, "gen-initrd.py"), "--triple", f"{arch}-managarm",
         "--sysroot", root, "-o", os.path.join(tree, "managarm/initrd.cpio")],
        check=True,
    )
    for eir in EIR_FILES[arch]:
        shutil.copy(os.path.join(bin_dir, eir), os.path.join(tree, "managarm"))
    shutil.copy(os.path.join(limine_dir, EFI_LOADERS[arch]), os.path.join(tree, "EFI/BOOT"))
    targets = installed_targets(root)
    write_limine_conf(os.path.join(tree, "limine.conf"), config, arch=arch, targets=targets)

    files = hash_tree(tree)
    # limine-bios.sys has to match the stages on the disk, so it is tracked by the root's copy that was
    # last paired with them, not by its content on the ESP.
    external = {}
    if has_bios_boot:
        external["limine-bios.sys"] = hash_file(os.path.join(limine_dir, "limine-bios.sys"))
    return files, external


def cmd_update_esp(args):
    config = Config.load(args.root)
    if not config.esp_partuuid:
        raise ConfigError(f"{args.root}: etc/managarm/partitions.toml does not set esp.partuuid")
    disk, esp, has_bios_boot = find_esp(config.esp_partuuid)

    limine_dir = os.path.join(args.root, "usr/share/limine")
    mtools_env = {**os.environ, "MTOOLS_SKIP_CHECK": "1"}

    with tempfile.TemporaryDirectory() as tree:
        files, external = make_esp_tree(args.root, args.arch, config, tree, has_bios_boot=has_bios_boot)

        old = read_stamp(esp, mtools_env)
        if not args.force and old is not None and old["files"] == files and old["external"] == external:
            print("update-boot: The boot files are up to date")
            return

        if old is not None:
            # Without a stamp, the next run redoes all of an update that this run does not finish.
            subprocess.run(["mdel", "-i", f"/dev/{esp}", f"::{STAMP_PATH}"], check=True, env=mtools_env)
            os.sync()

        if old is not None and not args.force:
            for path, digest in files.items():
                if old["files"].get(path) == digest:
                    os.unlink(os.path.join(tree, path))
            # Only files that an earlier run wrote are removed; the ESP may be shared. A file that is gone
            # already does not fail the run.
            for path in old["files"].keys() - files.keys():
                subprocess.run(["mdel", "-i", f"/dev/{esp}", f"::{path}"], env=mtools_env)

        # -s merges into directories that exist already and creates the others, and -o overwrites existing files.
        sources = [os.path.join(tree, f) for f in os.listdir(tree)]
        subprocess.run(["mcopy", "-s", "-o", "-i", f"/dev/{esp}", *sources, "::/"], check=True, env=mtools_env)

        # The stages must come from the same Limine build as limine-bios.sys on the ESP.
        paired_bios_sys = None if old is None or args.force else old["external"].get("limine-bios.sys")
        if has_bios_boot and paired_bios_sys != external["limine-bios.sys"]:
            subprocess.run(["mcopy", "-o", "-i", f"/dev/{esp}", os.path.join(limine_dir, "limine-bios.sys"), "::/"],
                           check=True, env=mtools_env)
            limine = os.path.join(args.root, "usr/bin/limine")
            subprocess.run([limine, "bios-install", f"/dev/{disk}"], check=True)

        # The stamp commits the update, so everything else must be on the disk before it.
        os.sync()
        stamp_path = os.path.join(tree, "update-boot.json")
        write_stamp(stamp_path, files, external)
        subprocess.run(["mcopy", "-o", "-i", f"/dev/{esp}", stamp_path, f"::{STAMP_PATH}"], check=True, env=mtools_env)

    os.sync()


def main():
    parser = argparse.ArgumentParser(description="Update the boot files of a Managarm installation")
    subparsers = parser.add_subparsers(dest="command", required=True)

    root_parser = argparse.ArgumentParser(add_help=False)
    root_parser.add_argument(
        "--root", default="/", help="Root of the installation (default: /)"
    )
    root_parser.add_argument(
        "--arch",
        choices=ARCHES,
        default=platform.machine(),
        help="Target architecture (default: uname -m)",
    )

    esp_parser = subparsers.add_parser(
        "esp-contents", parents=[root_parser],
        help="Write the generated ESP files and their stamp to a directory, except for limine-bios.sys"
    )
    esp_parser.add_argument(
        "--esp-dir", required=True, help="Empty directory that the ESP files are written to"
    )
    esp_parser.add_argument(
        "--bios-boot", action="store_true",
        help="The disk has a BIOS boot partition, whose Limine stages and limine-bios.sys the caller installs",
    )
    esp_parser.set_defaults(func=cmd_esp_contents)

    update_esp_parser = subparsers.add_parser(
        "update-esp", parents=[root_parser],
        help="Regenerate the boot files, write them to the ESP and install the Limine BIOS stages",
    )
    update_esp_parser.add_argument(
        "--force", action="store_true", help="Rewrite the ESP even if its stamp is up to date"
    )
    update_esp_parser.set_defaults(func=cmd_update_esp)

    args = parser.parse_args()

    # argparse does not check the default against the choices.
    if args.arch not in ARCHES:
        parser.error(f"unsupported architecture {args.arch!r}, pass --arch")

    try:
        args.func(args)
    except ConfigError as e:
        print(f"update-boot: {e}", file=sys.stderr)
        sys.exit(1)
    except subprocess.CalledProcessError as e:
        print(f"update-boot: {' '.join(e.cmd)} failed with status {e.returncode}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
